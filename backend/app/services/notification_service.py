"""
Communication & Notification component (design doc 1.7).

Two things live here, same grouping as the reference notification_service.py:

1. Announcements -- admin/committee-authored broadcasts, CRUD below.
2. Notifications -- per-user inbox items. `create_notification` and
   `notify_all_residents` are called FROM OTHER SERVICES (complaint_service,
   booking_service, visitor_service, auth_service, billing_service) to
   satisfy "Deliver real-time notifications for complaint updates,
   visitor approvals, and facility bookings" / "Notify residents about
   maintenance bill generation" (design doc 1.7) -- in the reference,
   notification_service existed but nothing outside this module ever
   called it, so no notification was ever actually generated by any
   real event. There is deliberately no public "create a notification
   for an arbitrary user" endpoint.
"""
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models.auth import Role, RoleEnum, User
from app.models.communication import Announcement, Notification
from app.models.mixins import ist_now
from app.schemas.communication_schema import AnnouncementCreate, AnnouncementUpdate
from app.utils.api_error import NotFound


# --------------------------------------------------------------------------
# Announcements
# --------------------------------------------------------------------------
def create_announcement(db: Session, payload: AnnouncementCreate) -> Announcement:
    announcement = Announcement(**payload.model_dump())
    db.add(announcement)
    db.commit()
    db.refresh(announcement)

    # "Broadcast emergency or community notices to relevant users" --
    # push it into every resident's notification inbox too, not just the
    # standalone announcements list.
    notify_all_residents(
        db,
        notification_type="announcement",
        title=announcement.title,
        message=(announcement.description or announcement.title)[:500],
    )
    return announcement


def list_announcements(db: Session, include_inactive: bool = False) -> list[Announcement]:
    stmt = select(Announcement)
    if not include_inactive:
        today = ist_now().date()
        stmt = stmt.where(
            Announcement.is_active.is_(True),
        ).where(
            (Announcement.expiry_date.is_(None)) | (Announcement.expiry_date >= today)
        )
    result = db.execute(stmt.order_by(Announcement.published_at.desc()))
    return list(result.scalars().all())


def get_announcement(db: Session, announcement_id: int) -> Announcement:
    result = db.execute(select(Announcement).where(Announcement.announcement_id == announcement_id))
    announcement = result.scalar_one_or_none()
    if announcement is None:
        raise NotFound("Announcement not found.")
    return announcement


def update_announcement(db: Session, announcement_id: int, payload: AnnouncementUpdate) -> Announcement:
    announcement = get_announcement(db, announcement_id)
    for field, value in payload.model_dump(exclude_unset=True).items():
        setattr(announcement, field, value)
    db.commit()
    db.refresh(announcement)
    return announcement


def delete_announcement(db: Session, announcement_id: int) -> None:
    announcement = get_announcement(db, announcement_id)
    db.delete(announcement)
    db.commit()


# --------------------------------------------------------------------------
# Notifications
# --------------------------------------------------------------------------
def create_notification(db: Session, user_id: int, notification_type: str, title: str, message: str) -> Notification:
    notification = Notification(
        user_id=user_id,
        notification_type=notification_type,
        title=title[:150],
        message=message,
    )
    db.add(notification)
    db.commit()
    db.refresh(notification)
    return notification


def notify_all_residents(db: Session, notification_type: str, title: str, message: str) -> None:
    """Fire-and-forget broadcast to every Resident user (verified or
    not -- announcements are informational, not gated on verification).
    """
    resident_user_ids = (
        db.query(User.user_id)
        .join(Role)
        .filter(Role.role_name == RoleEnum.RESIDENT)
        .all()
    )
    for (user_id,) in resident_user_ids:
        db.add(
            Notification(
                user_id=user_id,
                notification_type=notification_type,
                title=title[:150],
                message=message,
            )
        )
    db.commit()


def list_my_notifications(db: Session, user_id: int, unread_only: bool = False) -> list[Notification]:
    stmt = select(Notification).where(Notification.user_id == user_id)
    if unread_only:
        stmt = stmt.where(Notification.is_read.is_(False))
    result = db.execute(stmt.order_by(Notification.sent_at.desc()))
    return list(result.scalars().all())


def mark_notification_read(db: Session, notification_id: int, user_id: int) -> Notification:
    notification = (
        db.query(Notification)
        .filter(Notification.notification_id == notification_id, Notification.user_id == user_id)
        .first()
    )
    if notification is None:
        raise NotFound("Notification not found.")
    notification.is_read = True
    db.commit()
    db.refresh(notification)
    return notification


def mark_all_read(db: Session, user_id: int) -> int:
    updated = (
        db.query(Notification)
        .filter(Notification.user_id == user_id, Notification.is_read.is_(False))
        .update({"is_read": True})
    )
    db.commit()
    return updated